# -*- coding: utf-8 -*-
"""T08 caso 8 · Dos registros con la misma parcela dibujada: el segundo se rechaza en el mapa."""
import sys, pathlib; sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
from uilib import *

# coordenadas fijas para esta corrida (las dos parcelas se dibujan en el mismo lugar)
LAT, LNG = 23.1 + random.uniform(0, 1.0), -106.4 + random.uniform(0, 1.0)

def registro(pg, curp, nombre):
    pg.get_by_role('button', name='Nuevo registro').first.click(); pg.wait_for_timeout(1000)
    paso1(pg, curp); pg.get_by_role('button', name='Continuar').click(); pg.wait_for_timeout(800)
    paso2(pg, vacio_primero=False); paso3(pg)
    pg.get_by_role('button', name='Agregar la parcela').click(); pg.wait_for_timeout(400)
    pg.locator('input').nth(0).fill(nombre)
    pg.locator('select').nth(0).select_option(label='Durango'); pg.wait_for_timeout(1200)
    pg.locator('select').nth(1).select_option(label='Durango')
    pg.locator('input').nth(1).fill('Ejido San Jose')
    pg.get_by_role('button', name='Certificado parcelario').click(); pg.get_by_role('button', name='Temporal (lluvia)').click()
    abrir_mapa_y_dibujar(pg, LAT, LNG); terminar_poligono(pg)
    pg.get_by_role('button', name='Siguiente').click(); pg.wait_for_timeout(600)
    paso5(pg); paso6(pg)
    pg.get_by_role('checkbox', name=re.compile('Confirmo que la información')).click()
    pg.get_by_role('button', name='Enviar registro').click(); pg.wait_for_timeout(4500)

with sync_playwright() as p:
    br = p.chromium.launch()
    ctx = br.new_context(viewport={'width': 390, 'height': 844}, service_workers='block'); pg = ctx.new_page()
    entrar(pg)
    registro(pg, curp_nueva('REN'), 'Parcela original')
    ok('el primer registro se envia', pg.get_by_text('Registro enviado').count() >= 1)
    pg.get_by_role('button', name='Ir al inicio').click(); pg.wait_for_timeout(1500)
    curp2 = curp_nueva('REN')
    pg.get_by_role('button', name='Nuevo registro').first.click(); pg.wait_for_timeout(1000)
    paso1(pg, curp2); pg.get_by_role('button', name='Continuar').click(); pg.wait_for_timeout(800)
    paso2(pg, vacio_primero=False); paso3(pg)
    pg.get_by_role('button', name='Agregar la parcela').click(); pg.wait_for_timeout(400)
    pg.locator('input').nth(0).fill('Misma parcela otra persona')
    pg.locator('select').nth(0).select_option(label='Durango'); pg.wait_for_timeout(1200)
    pg.locator('select').nth(1).select_option(label='Durango')
    pg.locator('input').nth(1).fill('Ejido San Jose')
    pg.get_by_role('button', name='Certificado parcelario').click(); pg.get_by_role('button', name='Temporal (lluvia)').click()
    abrir_mapa_y_dibujar(pg, LAT, LNG)
    pg.get_by_role('button', name='Cerrar polígono').click(); pg.wait_for_timeout(2500)
    ok('el mapa avisa del traslape con la parcela de otro productor', pg.get_by_text('con la parcela de otro productor').count() >= 1, pg.get_by_text('con la parcela de otro productor').first.inner_text() if pg.get_by_text('con la parcela de otro productor').count() else '')
    shot(pg, 'caso8_traslape')
    ok('no deja usar esa parcela (no aparece "Parcela dibujada")', pg.get_by_text('Parcela dibujada').count() == 0)
    ok('no se creo el segundo productor', val(f"select count(*) from productor where curp='{curp2}'") == '0')
    ctx.close(); br.close()
